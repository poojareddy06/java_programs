public class first {
    public static void main(String[] args) {
        int a=19;
        if(a==18){
            System.out.println("dog is barking");
        }
        else if(a==19){
            System.out.println("dog is barking louder");
        }
        else{
            System.out.println("dog is not barking");
        }
    }
}
